#!/usr/bin/env python3
"""Generate steady flow-past-a-cylinder input files for the Re sweep in
cylinder_base.i and run them.

Re = 10, 20, 40 -- the three steady, symmetric cases below the ~Re = 47
vortex-shedding threshold, and the ones the reference tables this case is scored
against (Dennis & Chang 1970, DEB08 Table 2) report. cylinder_base.i fixes D = 1 (zone 5's
bounding box) and U = 1 (zone 1's inlet), so Re = U*D/nu = 1/nu and -visc is the
only knob that varies; it is derived here from Re rather than listed per case.
All three share flow-past-a-cylinder.msh -- a fixed mesh keeps the sweep
apples-to-apples, at the cost of carrying the same bias into every case (C_D runs
+13.6% against Dennis & Chang and +8.1% against DEB08 at Re = 40; see
docs/to-do-list-09-22-2026.md item 13 and report_drag.py's printed comparison).
run_blockage_study.py has since shown that only ~2.3 of those points come from
the mesh's 7.7% blockage, so the rest is discretization; pass --mesh/--tag below
to rerun this sweep on that study's effectively-unbounded Ly = 26 mesh.

n_timestep/dt per case were chosen so the per-step u/v L2 error is driven below
~1e-7 by the last step (inspect "<name>_out_convergence.csv"): the base file's
dt = 0.05 / 1400 steps (t = 70, ~2.7 flow-through times over the 26D-long domain)
gets Re = 10 to 6e-8, but the residual decays more slowly as Re rises, so Re = 20
and Re = 40 get extra steps below. C_D itself is the fast-converging quantity --
it is already stationary to 6 significant figures ~1000 steps before the residual
bottoms out at Re = 40 -- so the overrides buy confidence, not a different answer.

Run from anywhere; it resolves paths relative to this file and executes
build/inc_exec from the repo root (required for the relative mesh path in
the input files to resolve).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

RE_NUMBERS = [10, 20, 40]

# Re -> n_timestep, for cases that need more than the base file's 1400 to settle
# (see the module docstring). output_interval scales with n_timestep to keep
# ~14 output frames, matching the base file's 1400/100.
STEP_OVERRIDES = {
    20: 1800,
    40: 5000,
}

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR.parent.parent
BASE_INPUT = THIS_DIR / "cylinder_base.i"
INC_EXEC = REPO_ROOT / "build" / "inc_exec"


def sub_option(option, value, text):
    pattern = rf"^-{option} .*$"
    # Replacement via a lambda, not a string: a mesh path reaches this as `value`,
    # and re.subn would otherwise read a backslash in one as a group reference.
    new_text, n = re.subn(pattern, lambda _m: f"-{option} {value}", text, flags=re.MULTILINE)
    if n != 1:
        raise RuntimeError(f"expected exactly one '-{option}' line in {BASE_INPUT}, found {n}")
    return new_text


def case_path(Re_num, suffix, tag=""):
    return THIS_DIR / f"cylinder{tag}_Re{Re_num}{suffix}"


def make_input(Re_num, mesh=None, tag=""):
    visc = 1.0 / Re_num  # D = 1, U = 1

    text = BASE_INPUT.read_text()
    text = sub_option("visc", f"{visc:.8g}", text)

    note = f"Re = {Re_num}, D = 1, U = 1, visc = {visc:.6g}"
    if mesh is not None:
        text = sub_option("mesh", mesh, text)
        note += f", mesh = {mesh}"
    n_timestep = STEP_OVERRIDES.get(Re_num)
    if n_timestep is not None:
        text = sub_option("n_timestep", n_timestep, text)
        text = sub_option("output_interval", n_timestep // 14, text)
        note += f", n_timestep = {n_timestep} (bumped from the base file's 1400 for convergence)"

    text = f"# Generated by run_Re_sweep.py from {BASE_INPUT.name}: {note}\n" + text

    out_path = case_path(Re_num, ".i", tag)
    out_path.write_text(text)
    return out_path


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mesh", default=None, metavar="PATH",
                        help="override the base file's -mesh, as a path relative to the repo "
                             "root (e.g. benchmark/flow_pass_cylinder/blockage/cylinder_Ly26.msh, "
                             "the effectively-unbounded domain run_blockage_study.py found). "
                             "Requires --tag so the generated files and their CSVs do "
                             "not collide with the default sweep's.")
    parser.add_argument("--tag", default="", metavar="TAG",
                        help="name fragment inserted into the generated file names, as "
                             "cylinder<TAG>_Re<Re>.i -- pass e.g. _Ly26")
    args = parser.parse_args()

    if args.mesh and not args.tag:
        sys.exit("ERROR: --mesh needs --tag, otherwise this overwrites the default sweep's "
                 "inputs and its cylinder_Re<Re>_out_* CSVs with results from a "
                 "different mesh.")
    if args.mesh and not (REPO_ROOT / args.mesh).is_file():
        sys.exit(f"ERROR: mesh {REPO_ROOT / args.mesh} not found.")
    if not INC_EXEC.is_file():
        sys.exit(f"ERROR: {INC_EXEC} not found. Build first (see compile.sh).")

    input_files = {Re_num: make_input(Re_num, args.mesh, args.tag) for Re_num in RE_NUMBERS}
    for Re_num, path in input_files.items():
        print(f"wrote {path.relative_to(REPO_ROOT)}")

    procs = {}
    log_files = {}
    for Re_num, path in input_files.items():
        log_path = case_path(Re_num, ".log", args.tag)
        log_file = open(log_path, "w")
        proc = subprocess.Popen(
            [str(INC_EXEC), "-i", str(path.relative_to(REPO_ROOT))],
            cwd=REPO_ROOT,
            stdout=log_file,
            stderr=subprocess.STDOUT,
        )
        procs[Re_num] = proc
        log_files[Re_num] = log_file
        print(f"started Re={Re_num} (pid {proc.pid}), log: {log_path}")

    results = {}
    for Re_num, proc in procs.items():
        rc = proc.wait()
        log_files[Re_num].close()
        results[Re_num] = rc
        status = "OK" if rc == 0 else f"FAILED (rc={rc})"
        print(f"Re={Re_num}: {status}")

    ok = all(rc == 0 for rc in results.values())
    summary = "flow past a cylinder Re sweep: " + (
        f"all {len(results)} cases finished OK" if ok
        else "finished with failures: " + ", ".join(f"Re={Re_num}" for Re_num, rc in results.items() if rc != 0)
    )
    print(summary)

    if sys.platform == "darwin":
        subprocess.run(
            ["osascript", "-e", f'display notification "{summary}" with title "inc_ns benchmark"'],
            check=False,
        )


if __name__ == "__main__":
    main()
