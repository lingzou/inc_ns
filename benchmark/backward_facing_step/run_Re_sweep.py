#!/usr/bin/env python3
"""Generate backward-facing-step input files for the Re sweep and run them.

backward_facing_step_base.i fixes the inlet (parabolic profile, u_max = 1.5,
so u_avg = (2/3) * u_max = 1.0, h = 1) and only varies with -visc:
Re = u_avg * (2*h) / nu  ->  nu = 2 / Re. Unlike input/backward_facing_step.i's
Re = 300 case (which instead raises u_max to 2.25), every case here shares the
same inlet velocity and differs only in viscosity.

Re = 200 (the base file's own default) and Re = 300 (the separate
input/backward_facing_step.i case) have been checked against Armaly et al.
Re = 250/300/400 get extra steps below: their first run at the base file's
n_timestep = 2000 left u_L2_error at 2.7e-4 / 1.2e-3 / 5.1e-3 respectively,
decaying cleanly enough (~exponential over the last 1000+ steps, no
oscillation) to extrapolate the step count needed to drive each below ~1e-7.
Inspect "<name>_out_convergence.csv" before trusting a case not listed in
STEP_OVERRIDES or in the paragraph above.

Run from anywhere; it resolves paths relative to this file and executes
build/inc_exec from the repo root (required for the relative mesh path in
the input files to resolve).
"""
import re
import subprocess
import sys
from pathlib import Path

RE_NUMBERS = [50, 100, 150, 200, 250, 300, 400]

# Re -> n_timestep, for cases that need more than the base file's 2000 to bring
# u_L2_error down near ~1e-7 (see the module docstring). output_interval scales
# with n_timestep to keep ~20 output frames, matching the base file's 2000/100.
STEP_OVERRIDES = {
    250: 4000,
    300: 6000,
    400: 10000,
}

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR.parent.parent
BASE_INPUT = THIS_DIR / "backward_facing_step_base.i"
INC_EXEC = REPO_ROOT / "build" / "inc_exec"


def sub_option(option, value, text):
    pattern = rf"^-{option} .*$"
    replacement = f"-{option} {value}"
    new_text, n = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if n != 1:
        raise RuntimeError(f"expected exactly one '-{option}' line in {BASE_INPUT}, found {n}")
    return new_text


def make_input(Re_num):
    visc = 2.0 / Re_num
    text = BASE_INPUT.read_text()
    text = sub_option("visc", f"{visc:.6g}", text)

    n_timestep = STEP_OVERRIDES.get(Re_num)
    note = f"Re = {Re_num}, visc = {visc:.6g}"
    if n_timestep is not None:
        output_interval = n_timestep // 20
        text = sub_option("n_timestep", n_timestep, text)
        text = sub_option("output_interval", output_interval, text)
        note += f", n_timestep = {n_timestep} (bumped from the base file's 2000 for convergence)"

    text = f"# Generated by run_Re_sweep.py from {BASE_INPUT.name}: {note}\n" + text

    out_path = THIS_DIR / f"backward_facing_step_Re{Re_num}.i"
    out_path.write_text(text)
    return out_path


def main():
    if not INC_EXEC.is_file():
        sys.exit(f"ERROR: {INC_EXEC} not found. Build first (see compile.sh).")

    input_files = {Re_num: make_input(Re_num) for Re_num in RE_NUMBERS}
    for Re_num, path in input_files.items():
        print(f"wrote {path.relative_to(REPO_ROOT)}")

    procs = {}
    log_files = {}
    for Re_num, path in input_files.items():
        log_path = THIS_DIR / f"backward_facing_step_Re{Re_num}.log"
        log_file = open(log_path, "w")
        proc = subprocess.Popen(
            [str(INC_EXEC), "-i", str(path.relative_to(REPO_ROOT))],
            cwd=REPO_ROOT,
            stdout=log_file,
            stderr=subprocess.STDOUT,
        )
        procs[Re_num] = proc
        log_files[Re_num] = log_file
        print(f"started Re={Re_num} (pid {proc.pid}), log: {log_path}")

    results = {}
    for Re_num, proc in procs.items():
        rc = proc.wait()
        log_files[Re_num].close()
        results[Re_num] = rc
        status = "OK" if rc == 0 else f"FAILED (rc={rc})"
        print(f"Re={Re_num}: {status}")

    ok = all(rc == 0 for rc in results.values())
    summary = "backward-facing step Re sweep: " + (
        f"all {len(results)} cases finished OK" if ok
        else "finished with failures: " + ", ".join(f"Re={Re_num}" for Re_num, rc in results.items() if rc != 0)
    )
    print(summary)

    if sys.platform == "darwin":
        subprocess.run(
            ["osascript", "-e", f'display notification "{summary}" with title "inc_ns benchmark"'],
            check=False,
        )


if __name__ == "__main__":
    main()
