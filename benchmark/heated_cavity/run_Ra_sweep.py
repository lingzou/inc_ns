#!/usr/bin/env python3
"""Generate differentially heated cavity input files for the Ra sweep in
cavity_buoyancy_base.i and run them.

Ra = 1e3, 1e4, 1e5, 1e6, Pr = 0.71, de Vahl Davis (1983) / DEB08 section 4.5
nondimensionalization: -visc = sqrt(Pr/Ra), -diff_t = 1/sqrt(Ra*Pr) (derived
here from Ra/Pr directly, rather than copy-pasted per case). All four cases
share cavity_60.msh -- a fixed mesh keeps the sweep apples-to-apples, at the
cost of under-resolving the thin boundary layers at Ra = 1e6 (see the base
file's -nusselt_zones comment and report_nusselt.py's printed comparison
against de Vahl Davis's reference table).

n_timestep/dt per case were chosen so the per-step u/v/T L2 error has bottomed
out by the last step (inspect "<name>_out_convergence.csv"): Ra = 1e5 reuses
the known-good input/cavity_buoyancy_1e5.i (dt = 0.05, 4000 steps); Ra = 1e6's
stronger convection needs a smaller dt and more steps.

Run from anywhere; it resolves paths relative to this file and executes
build/inc_exec from the repo root (required for the relative mesh path in
the input files to resolve).
"""
import math
import re
import subprocess
import sys
from pathlib import Path

PR = 0.71  # matches cavity_buoyancy_base.i's own comment

# Ra -> (dt, n_timestep, output_interval). visc/diff_t are derived from Ra/PR
# below, not listed here, so they can never drift out of sync with each other.
CASES = {
    1e3: dict(dt=0.05, n_timestep=3000,  output_interval=100),
    1e4: dict(dt=0.05, n_timestep=3500,  output_interval=100),
    1e5: dict(dt=0.05, n_timestep=4000,  output_interval=100),
    1e6: dict(dt=0.02, n_timestep=10000, output_interval=200),
}

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR.parent.parent
BASE_INPUT = THIS_DIR / "cavity_buoyancy_base.i"
INC_EXEC = REPO_ROOT / "build" / "inc_exec"


def sub_option(option, value, text):
    pattern = rf"^-{option} .*$"
    replacement = f"-{option} {value}"
    new_text, n = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if n != 1:
        raise RuntimeError(f"expected exactly one '-{option}' line in {BASE_INPUT}, found {n}")
    return new_text


def ra_label(Ra):
    return f"1e{round(math.log10(Ra))}"


def case_path(Ra, suffix):
    return THIS_DIR / f"cavity_buoyancy_Ra{ra_label(Ra)}{suffix}"


def make_input(Ra, params):
    visc = math.sqrt(PR / Ra)
    diff_t = 1.0 / math.sqrt(Ra * PR)

    text = BASE_INPUT.read_text()
    text = sub_option("visc", f"{visc:.8g}", text)
    text = sub_option("diff_t", f"{diff_t:.8g}", text)
    for option in ("dt", "n_timestep", "output_interval"):
        text = sub_option(option, params[option], text)

    note = f"Ra = {Ra:g}, Pr = {PR}, visc = {visc:.6g}, diff_t = {diff_t:.6g}"
    text = f"# Generated by run_Ra_sweep.py from {BASE_INPUT.name}: {note}\n" + text

    out_path = case_path(Ra, ".i")
    out_path.write_text(text)
    return out_path


def main():
    if not INC_EXEC.is_file():
        sys.exit(f"ERROR: {INC_EXEC} not found. Build first (see compile.sh).")

    input_files = {Ra: make_input(Ra, params) for Ra, params in CASES.items()}
    for Ra, path in input_files.items():
        print(f"wrote {path.relative_to(REPO_ROOT)}")

    procs = {}
    log_files = {}
    for Ra, path in input_files.items():
        log_path = case_path(Ra, ".log")
        log_file = open(log_path, "w")
        proc = subprocess.Popen(
            [str(INC_EXEC), "-i", str(path.relative_to(REPO_ROOT))],
            cwd=REPO_ROOT,
            stdout=log_file,
            stderr=subprocess.STDOUT,
        )
        procs[Ra] = proc
        log_files[Ra] = log_file
        print(f"started Ra={Ra:g} (pid {proc.pid}), log: {log_path}")

    results = {}
    for Ra, proc in procs.items():
        rc = proc.wait()
        log_files[Ra].close()
        results[Ra] = rc
        status = "OK" if rc == 0 else f"FAILED (rc={rc})"
        print(f"Ra={Ra:g}: {status}")

    ok = all(rc == 0 for rc in results.values())
    summary = "heated cavity Ra sweep: " + (
        f"all {len(results)} cases finished OK" if ok
        else "finished with failures: " + ", ".join(f"Ra={Ra:g}" for Ra, rc in results.items() if rc != 0)
    )
    print(summary)

    if sys.platform == "darwin":
        subprocess.run(
            ["osascript", "-e", f'display notification "{summary}" with title "inc_ns benchmark"'],
            check=False,
        )


if __name__ == "__main__":
    main()
